# Cell 18: Full Code for Two-Stage Hybrid Engine
nb['cells'][18]['source'] = [
    'import easyocr\n',
    '\n',
    '# Initialize OCR reader on GPU/CPU once (singleton)\n',
    'OCR_READER = easyocr.Reader(["en"], gpu=(DEVICE.type == "cuda"), verbose=False)\n',
    '\n',
    '# Denomination numeral and keyword patterns\n',
    'DENOM_PATTERNS = {\n',
    '    "2000": [r"(?:\\b|₹|rs\\.?|r)2000\\b", r"\\b2ooo\\b", r"two\\s*thousand"],\n',
    '    "500":  [r"(?:\\b|₹|rs\\.?|r)500\\b",  r"\\b5oo\\b",  r"\\b5o0\\b", r"five\\s*hundred"],\n',
    '    "200":  [r"(?:\\b|₹|rs\\.?|r)200\\b",  r"\\b2oo\\b",  r"\\b2o0\\b", r"two\\s*hundred"],\n',
    '    "100":  [r"(?:\\b|₹|rs\\.?|r)100\\b",  r"\\b1oo\\b",  r"\\b1o0\\b", r"one\\s*hundred", r"hundred\\s*rupees"],\n',
    '    "50":   [r"(?:\\b|₹|rs\\.?|r)50\\b",   r"\\b5o\\b",   r"fifty\\s*rupees"],\n',
    '    "20":   [r"(?:\\b|₹|rs\\.?|r)20\\b",   r"\\b2o\\b",   r"twenty\\s*rupees"],\n',
    '    "10":   [r"(?:\\b|₹|rs\\.?|r)10\\b",   r"\\b1o\\b",   r"ten\\s*rupees"]\n',
    '}\n',
    '\n',
    'def spot_currency_numerals(pil_image):\n',
    '    \"\"\"\n',
    '    Stage 1: Orientation-aware OCR Numeral Spotter.\n',
    '    Scans image for printed denomination digits (e.g. 500, 200, 50).\n',
    '    Returns: (detected_denomination, matched_keyword, detected_text) or (None, None, \"\")\n',
    '    \"\"\"\n',
    '    w, h = pil_image.size\n',
    '    # Check both horizontal orientations and vertical rotations\n',
    '    rotations = [270, 90, 0, 180] if h > w else [0, 180, 270, 90]\n',
    '    \n',
    '    for rot in rotations:\n',
    '        img_rot = pil_image.rotate(rot, expand=True) if rot != 0 else pil_image\n',
    '        results = OCR_READER.readtext(np.array(img_rot))\n',
    '        full_text = \" \".join([t.lower() for _, t, conf in results if conf >= 0.25])\n',
    '        \n',
    '        # Check longer denominations first (2000, 500, 200, 100, 50, 20, 10)\n',
    '        for denom in [\"2000\", \"500\", \"200\", \"100\", \"50\", \"20\", \"10\"]:\n',
    '            for pattern in DENOM_PATTERNS[denom]:\n',
    '                if re.search(pattern, full_text):\n',
    '                    return denom, pattern, full_text\n',
    '    return None, None, \"\"\n',
    '\n',
    'def predict_currency_vision(pil_image):\n',
    '    \"\"\"\n',
    '    Stage 2: Deep Vision Feature Extractor (Fallback).\n',
    '    Uses ConvNeXt-Tiny with letterbox padding.\n',
    '    \"\"\"\n',
    '    w, h = pil_image.size\n',
    '    scale = IMG_SIZE / max(w, h)\n',
    '    new_w, new_h = int(w * scale), int(h * scale)\n',
    '    resized = pil_image.resize((new_w, new_h), Image.Resampling.BILINEAR)\n',
    '    canvas = Image.new(\"RGB\", (IMG_SIZE, IMG_SIZE), (0, 0, 0))\n',
    '    canvas.paste(resized, ((IMG_SIZE - new_w) // 2, (IMG_SIZE - new_h) // 2))\n',
    '    \n',
    '    x = eval_transform(canvas).unsqueeze(0).to(DEVICE)\n',
    '    with torch.inference_mode():\n',
    '        probabilities = torch.softmax(model(x), dim=1)[0].cpu().numpy()\n',
    '        \n',
    '    pred_idx = int(probabilities.argmax())\n',
    '    return CLASS_NAMES[pred_idx], float(probabilities[pred_idx]), probabilities\n',
    '\n',
    'def predict_currency_hybrid(image_input, confidence_threshold=0.70):\n',
    '    \"\"\"\n',
    '    Two-Stage Hybrid Assistive Inference Pipeline:\n',
    '    1. Stage 1 OCR Numeral Spotter -> 100% precision, background/color-immune.\n',
    '    2. Stage 2 Deep Vision -> Fallback when numerals are covered by fingers.\n',
    '    3. Assistive Voice Output Message.\n',
    '    \"\"\"\n',
    '    if isinstance(image_input, (str, Path)):\n',
    '        image = Image.open(image_input).convert(\"RGB\")\n',
    '    elif isinstance(image_input, np.ndarray):\n',
    '        image = Image.fromarray(image_input).convert(\"RGB\")\n',
    '    else:\n',
    '        image = image_input.convert(\"RGB\")\n',
    '        \n',
    '    # 1. Run Stage 1: OCR Numeral Spotting\n',
    '    ocr_denom, matched_pattern, full_text = spot_currency_numerals(image)\n',
    '    \n',
    '    # 2. Run Stage 2: Vision Model\n',
    '    vis_denom, vis_conf, vis_probs = predict_currency_vision(image)\n',
    '    \n',
    '    # 3. Decision Fusion Logic\n',
    '    if ocr_denom is not None:\n',
    '        # OCR spotted the printed numeral directly!\n',
    '        is_double_verified = (ocr_denom == vis_denom)\n',
    '        status = \"DOUBLE_VERIFIED\" if is_double_verified else \"OCR_NUMERAL_VERIFIED\"\n',
    '        conf = 1.0 if is_double_verified else 0.98\n',
    '        message = f\"Verified ₹{ocr_denom} rupee note detected (printed numeral spotted).\"\n',
    '        final_denom = ocr_denom\n',
    '        accepted = True\n',
    '    elif vis_conf >= confidence_threshold:\n',
    '        # Numerals obscured, but vision model is confident\n',
    '        status = \"VISION_VERIFIED\"\n',
    '        conf = vis_conf\n',
    '        message = f\"₹{vis_denom} rupee note detected with {vis_conf*100:.1f} percent confidence.\"\n',
    '        final_denom = vis_denom\n',
    '        accepted = True\n',
    '    else:\n',
    '        # Ambiguous / Low confidence / Background\n',
    '        status = \"UNRELIABLE\"\n',
    '        conf = vis_conf\n',
    '        message = \"Unable to verify the note. Please hold one banknote flat and centered in good light.\"\n',
    '        final_denom = vis_denom\n',
    '        accepted = False\n',
    '        \n',
    '    return {\n',
    '        \"accepted\": accepted,\n',
    '        \"denomination\": f\"₹{final_denom}\",\n',
    '        \"confidence\": round(conf * 100, 1),\n',
    '        \"verification_source\": status,\n',
    '        \"ocr_spotted\": f\"₹{ocr_denom}\" if ocr_denom else None,\n',
    '        \"vision_candidate\": f\"₹{vis_denom} ({vis_conf*100:.1f}%)\",\n',
    '        \"message\": message\n',
    '    }\n',
    '\n',
    'print(\"✅ Two-Stage Hybrid Engine initialized successfully!\")\n',
    '# Test on sample note:\n',
    'sample_test = list(Path(\"Indian Currency Dataset/500\").glob(\"*.jpg\"))[0]\n',
    'result = predict_currency_hybrid(sample_test)\n',
    'print(json.dumps(result, indent=2))\n'
]

